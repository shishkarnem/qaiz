    const cleanTopic = (mainGameTopic && typeof mainGameTopic === 'string' && !mainGameTopic.includes(','))
      ? mainGameTopic.trim()
      : (mainGameTopic ? mainGameTopic.split(',')[0].trim() : 'Общие знания');
