const AI_TIMEOUT_MS = 115000; // 115 seconds for question generation (server has 100s timeout)
const CHECK_TIMEOUT_MS = 60000; // 60 seconds for answer checking

function parseAIResponse(rawText: any): any {
  if (rawText === null || rawText === undefined) return null;
  if (typeof rawText !== 'string') return rawText;

  let cleaned = rawText.trim();

  // Strip <think>...</think> blocks if present
  cleaned = cleaned.replace(/<think>[\s\S]*?<\/think>/gi, '').trim();

  // If starts with AI Reasoning or Reasoning:, find start of JSON array or object
  if (cleaned.startsWith('AI Reasoning') || cleaned.includes('AI Reasoning (None):') || cleaned.startsWith('Reasoning:')) {
    const jsonArrIdx = cleaned.indexOf('[');
    const jsonObjIdx = cleaned.indexOf('{');
    const firstIdx = (jsonArrIdx !== -1 && jsonObjIdx !== -1)
      ? Math.min(jsonArrIdx, jsonObjIdx)
      : (jsonArrIdx !== -1 ? jsonArrIdx : jsonObjIdx);
    if (firstIdx !== -1) {
      cleaned = cleaned.substring(firstIdx).trim();
    }
  }

  // If string contains markdown code block, extract inner content
  const codeBlockMatch = cleaned.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
  if (codeBlockMatch && codeBlockMatch[1]) {
    cleaned = codeBlockMatch[1].trim();
  }

  try {
    const parsed = JSON.parse(cleaned);
    if (typeof parsed === 'string') {
      try {
        return JSON.parse(parsed);
      } catch (_) {
        return parsed;
      }
    }
    return parsed;
  } catch (_) {
    // Extract first [ to last ]
    const firstArr = cleaned.indexOf('[');
    const lastArr = cleaned.lastIndexOf(']');
    if (firstArr !== -1 && lastArr > firstArr) {
      try {
        return JSON.parse(cleaned.substring(firstArr, lastArr + 1));
      } catch (_) {}
    }

    // Extract first { to last }
    const firstObj = cleaned.indexOf('{');
    const lastObj = cleaned.lastIndexOf('}');
    if (firstObj !== -1 && lastObj > firstObj) {
      try {
        return JSON.parse(cleaned.substring(firstObj, lastObj + 1));
      } catch (_) {}
    }
  }
  return cleaned;
}

export function getProTalkUserId(): string {
  if (typeof window === 'undefined') return '10000000001';
  try {
    // 1. If registered user, use their real UID / ID
    const session = localStorage.getItem('user_session') || localStorage.getItem('user_email_session');
    if (session) {
      const parsed = JSON.parse(session);
      if (parsed?.uid) {
        localStorage.setItem('qaiz_active_user_id', String(parsed.uid));
        return String(parsed.uid);
      }
      if (parsed?.id) {
        localStorage.setItem('qaiz_active_user_id', String(parsed.id));
        return String(parsed.id);
      }
    }
    const userUid = localStorage.getItem('qaiz_user_uid');
    if (userUid && /^\d+$/.test(userUid)) {
      localStorage.setItem('qaiz_active_user_id', userUid);
      return userUid;
    }

    const active = localStorage.getItem('qaiz_active_user_id');
    if (active && active !== '169262990' && active !== 'usr_guest' && /^\d+$/.test(active)) return active;

    // 2. If demo user, use or create cached 11-digit UID
    const demo = localStorage.getItem('guest_demo_uid');
    if (demo && /^\d{11}$/.test(demo)) {
      localStorage.setItem('qaiz_active_user_id', demo);
      return demo;
    }
    const generated = String(Math.floor(10000000000 + Math.random() * 90000000000));
    localStorage.setItem('guest_demo_uid', generated);
    localStorage.setItem('qaiz_active_user_id', generated);
    return generated;
  } catch (_) {
    return '10000000001';
  }
}

async function callProTalkAI(prompt: string, mode: string = 'generate', gameId?: string, count?: number): Promise<any> {
  const isCheckMode = mode === 'check_answer' || mode === 'check';
  const isJeopardy = gameId === 'jeopardy' || 
    mode === 'jeopardy' || 
    mode?.startsWith('jeopardy') || 
    prompt.includes('Своя Икра') || 
    prompt.includes('раунд из 25 вопросов') || 
    prompt.includes('25 вопросов') ||
    prompt.includes('jeopardy');
  const currentTimeout = isJeopardy ? 245000 : (isCheckMode ? CHECK_TIMEOUT_MS : AI_TIMEOUT_MS);

  const controller = new AbortController();
  const timeoutId = window.setTimeout(() => controller.abort(), currentTimeout);

  const activeUserId = getProTalkUserId();
  const targetGame = gameId || (isJeopardy ? 'jeopardy' : mode) || 'blitz';
  const cleanGame = String(targetGame).replace(/[^a-zA-Z0-9]/g, '');
  const cleanUser = String(activeUserId).replace(/[^a-zA-Z0-9]/g, '');
  const chatId = `${cleanGame}${cleanUser}`;

  let res: Response;
  try {
    res = await fetch('/api/protalk', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ 
        prompt, 
        mode,
        user_id: cleanUser,
        game_id: cleanGame,
        chat_id: chatId,
        count: count || 1
      }),
      signal: controller.signal,
    });
  } catch (error) {
    if (error instanceof DOMException && error.name === 'AbortError') {
      const waitText = isJeopardy ? '240 секунд' : (isCheckMode ? '60 секунд' : '100 секунд');
      throw new Error(`ProTalk AI не ответил за ${waitText}. Попробуйте повторить запрос.`);
    }
    throw error;
  } finally {
    window.clearTimeout(timeoutId);
  }

  if (!res.ok) {
    const errData = await res.json().catch(() => ({ error: `HTTP ${res.status}` }));
    let rawError = errData.error || `ProTalk request failed: ${res.status}`;
    if (rawError.includes('502') || rawError.includes('Bad Gateway') || rawError.includes('<html')) {
      rawError = 'Сервер ProTalk кратковременно перезагружается (502 Bad Gateway). Пожалуйста, повторите попытку через пару секунд.';
    }
    throw new Error(rawError);
  }

  const data = await res.json();
  if (data.error) {
    let rawError = String(data.error);
    if (rawError.includes('502') || rawError.includes('Bad Gateway') || rawError.includes('<html')) {
      rawError = 'Сервер ProTalk кратковременно перезагружается (502 Bad Gateway). Пожалуйста, повторите попытку через пару секунд.';
    }
    throw new Error(rawError);
  }

  const raw = data.response !== undefined ? data.response : (data.reply || data.text || data.message || '');
  return parseAIResponse(raw);
}

